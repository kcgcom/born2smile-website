import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { NextRequest } from "next/server";
import { classifyAgentContentAccess } from "../lib/agent-content-access";
import { mapPlannerRow } from "../lib/content-planner";
import { taskCommandSchema, taskProposalSchema, taskWorkflow } from "../lib/content-tasks";
import { planTaskCommand, taskHash, taskView, type TaskRow } from "../lib/content-tasks-server";
import { collectionTaskRequest, taskRequest, taskSessionSchema } from "./agent/task";
import { taskDraftSlug } from "../lib/content-task-drafts";

process.env.AGENT_CONTENT_SECRET = "task-test-secret";
process.env.ADMIN_CLI_SECRET = "admin-test-secret";
process.env.ADMIN_EMAILS = "admin@example.invalid";
process.env.NEXT_PUBLIC_SUPABASE_URL = "http://127.0.0.1:54321";
process.env.SUPABASE_SERVICE_ROLE_KEY = "test-only-service-role";
const rows = new Map<string, TaskRow>();
const posts = new Map<string, Record<string, unknown>>();
const proposal = { proposalKey: "test-proposal", workerId: "worker-one", itemType: "blog", title: "임플란트 관리 설명 보강", category: "implant", targetPage: "/blog/implant/example-post", rationale: "환자 질문에 대한 설명이 부족합니다.", scope: ["관리 방법 보강"], acceptanceCriteria: ["근거와 금기 사항 확인"], evidence: [{ source: "reader-feedback", summary: "관리 방법에 대한 미해결 질문이 반복됩니다." }] };
let databaseCalls = 0;
const originalFetch = globalThis.fetch;
globalThis.fetch = async (input, init) => {
  databaseCalls++;
  const request = new Request(input, init);
  const url = new URL(request.url);
  assert.equal(url.origin, "http://127.0.0.1:54321", "Network must remain isolated");
  if (url.pathname === "/auth/v1/user") return Response.json({ id: randomUUID(), email: "admin@example.invalid", app_metadata: {}, user_metadata: {}, aud: "authenticated", created_at: new Date().toISOString() });
  const table = url.pathname.split("/").at(-1);
  const single = request.headers.get("accept")?.includes("vnd.pgrst.object");
  const respond = (values: unknown[]) => Response.json(single ? values[0] ?? null : values);
  if (table === "blog_content_revisions") return respond([{ id: randomUUID(), slug: "example-post", status: "draft" }]);
  if (table === "blog_posts") {
    if (request.method === "POST") {
      const body = await request.json();
      if (posts.has(body.slug)) return Response.json({ code: "23505" }, { status: 409 });
      posts.set(body.slug, body);
      return new Response(null, { status: 201 });
    }
    const slug = url.searchParams.get("slug")?.replace(/^eq\./, "");
    return respond(slug === "example-post" ? [{ slug, published: false }] : slug && posts.has(slug) ? [posts.get(slug)] : []);
  }
  assert.equal(table, "content_planner_items");
  const eq = (key: string) => url.searchParams.get(key)?.replace(/^eq\./, "");
  const matching = () => [...rows.values()].filter(row => ["id", "opportunity_key", "status", "updated_at"].every(key => !eq(key) || row[key as keyof TaskRow] === eq(key)));
  if (request.method === "GET") return respond(structuredClone(matching()));
  const body = await request.json();
  if (request.method === "POST") {
    if ([...rows.values()].some(row => row.opportunity_key === body.opportunity_key)) return Response.json({ code: "23505", message: "duplicate" }, { status: 409 });
    const row: TaskRow = { id: randomUUID(), due_date: null, created_at: new Date().toISOString(), updated_at: new Date().toISOString(), ...body };
    rows.set(row.id, row);
    return respond([structuredClone(row)]);
  }
  assert.equal(request.method, "PATCH");
  const saved = matching().map(row => { const next = { ...row, ...body }; rows.set(row.id, next); return next; });
  return respond(structuredClone(saved));
};

async function verify() {
  const collection = await import("../app/api/admin/content-tasks/route");
  const task = await import("../app/api/admin/content-tasks/[id]/route");
  const human = await import("../app/api/admin/content-planner/[id]/route");
  const draft = await import("../app/api/admin/content-tasks/[id]/draft/route");
  const secret = process.env.AGENT_CONTENT_SECRET!;
  const request = (path: string, method = "GET", body?: unknown, token = secret) => new NextRequest(`http://localhost:3000${path}`, { method, headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json" }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  assert(taskProposalSchema.safeParse(proposal).success);
  assert(!taskProposalSchema.safeParse({ ...proposal, status: "approved" }).success);
  assert(!taskProposalSchema.safeParse({ ...proposal, targetPage: "//evil.test" }).success);
  assert(!taskCommandSchema.safeParse({ action: "publish", baseUpdatedAt: new Date().toISOString() }).success);
  let response = await collection.POST(request("/api/admin/content-tasks", "POST", proposal));
  assert.equal(response.status, 201);
  const created = (await response.json()).data;
  const id = created.id;
  const path = `/api/admin/content-tasks/${id}`;
  const context = { params: Promise.resolve({ id }) };
  assert.equal(created.status, "deferred");
  assert(!JSON.stringify(created).includes("proposalHash"));
  assert.equal((await collection.POST(request("/api/admin/content-tasks", "POST", proposal))).status, 200);
  assert.equal((await collection.POST(request("/api/admin/content-tasks", "POST", { ...proposal, title: "다른 제안 제목" }))).status, 409);
  assert.equal(rows.size, 1);
  const command = (body: unknown) => task.PATCH(request(path, "PATCH", body), context);
  assert.equal((await command({ action: "claim", workerId: "worker-one", baseUpdatedAt: created.updatedAt })).status, 409);
  const before = databaseCalls;
  assert.equal((await human.PUT(request(`/api/admin/content-planner/${id}`, "PUT", { status: "approved" }), context)).status, 403);
  assert.equal(databaseCalls, before);
  const approve = await human.PUT(request(`/api/admin/content-planner/${id}`, "PUT", { status: "approved", baseUpdatedAt: created.updatedAt }, "browser-test-token"), context);
  assert.equal(approve.status, 200);
  const approved = (await approve.json()).data;
  const claims = await Promise.all([command({ action: "claim", workerId: "worker-one", baseUpdatedAt: approved.updatedAt }), command({ action: "claim", workerId: "worker-two", baseUpdatedAt: approved.updatedAt })]);
  assert.deepEqual(claims.map(r => r.status).sort(), [200, 409]);
  const claimed = await claims.find(r => r.status === 200)!.json();
  assert.match(claimed.claimToken, /^[a-f0-9]{64}$/);
  const stored = rows.get(id)!;
  assert(!JSON.stringify(stored).includes(claimed.claimToken));
  assert(!JSON.stringify(taskView(stored)).includes("claimHash"));
  assert(!JSON.stringify(mapPlannerRow(stored)).includes("claimHash"));
  response = await command({ action: "progress", baseUpdatedAt: stored.updated_at, claimToken: "0".repeat(64), message: "진행 보고" });
  assert.equal(response.status, 409);
  response = await command({ action: "progress", baseUpdatedAt: stored.updated_at, claimToken: claimed.claimToken, message: "출처 확인 중", blockedReason: "원문 확인 필요" });
  assert.equal(response.status, 200);
  assert.equal(taskWorkflow(rows.get(id)!.source_snapshot).blockedReason, "원문 확인 필요");
  const result = { kind: "revision", postSlug: "example-post", revisionId: randomUUID(), summary: "관리 방법 설명을 보강한 수정안입니다." };
  const submission = { action: "submit", baseUpdatedAt: rows.get(id)!.updated_at, claimToken: claimed.claimToken, requestId: randomUUID(), result };
  const wrong = await command({ ...submission, result: { ...result, postSlug: "other-post" } });
  assert.equal(wrong.status, 400);
  response = await command(submission);
  assert.equal(response.status, 200);
  assert.equal(rows.get(id)!.status, "review");
  const submittedVersion = rows.get(id)!.updated_at;
  response = await command(submission);
  assert.equal(response.status, 200);
  assert.equal((await response.json()).replayed, true);
  assert.equal(rows.get(id)!.updated_at, submittedVersion);
  assert.equal((await command({ ...submission, result: { ...result, summary: "같은 요청 ID로 변경한 다른 결과입니다." } })).status, 409);
  const expired = { ...stored, status: "in_progress" as const, source_snapshot: { taskWorkflow: { version: 1, claimHash: taskHash(claimed.claimToken), leaseExpiresAt: new Date(0).toISOString() } } };
  assert.throws(() => planTaskCommand(expired, taskCommandSchema.parse({ action: "progress", baseUpdatedAt: expired.updated_at, claimToken: claimed.claimToken, message: "만료된 보고" })), /점유 토큰/);
  const again = planTaskCommand(expired, taskCommandSchema.parse({ action: "claim", baseUpdatedAt: expired.updated_at, workerId: "recovery-worker" }));
  assert.equal(again.replayed, false);
  const secrets = { content: secret, admin: "admin-test-secret" };
  for (const [method, target] of [["POST", "/api/admin/content-tasks"], ["PATCH", path], ["GET", path]]) assert.equal(classifyAgentContentAccess(secret, method, target, secrets), "agent:content");
  for (const [method, target] of [["PUT", `/api/admin/content-planner/${id}`], ["POST", "/api/admin/blog-posts"], ["DELETE", path], ["POST", `${path}/approve`]]) assert.equal(classifyAgentContentAccess(secret, method, target, secrets), "denied");
  assert.equal((await collection.POST(request("/api/admin/content-tasks", "POST", { ...proposal, extra: "x".repeat(70_000) }))).status, 413);
  // New article: proposal -> human approval -> claim -> private draft -> review -> rework -> completion.
  const createdNew = await collection.POST(request("/api/admin/content-tasks", "POST", { ...proposal, proposalKey: "new-blog-task", targetPage: "/treatments/implant" }));
  const fresh = (await createdNew.json()).data;
  const newContext = { params: Promise.resolve({ id: fresh.id }) };
  const newPath = `/api/admin/content-tasks/${fresh.id}`;
  const candidate = { title: "임플란트 관리 안내 원고", subtitle: "환자에게 필요한 관리 안내입니다", excerpt: "환자에게 필요한 관리 방법과 상담이 필요한 상황을 정리했습니다.", category: "implant", tags: [], blocks: [{ type: "paragraph", text: "시술 후 관리 방법과 주의할 점은 개인의 상태에 따라 달라지므로 담당 의료진에게 확인해야 합니다." }] };
  const draftPath = `${newPath}/draft`;
  assert.equal((await draft.POST(request(draftPath, "POST", { candidate, baseUpdatedAt: fresh.updatedAt, claimToken: "0".repeat(64) }), newContext)).status, 409);
  const newApproval = await human.PUT(request(`/api/admin/content-planner/${fresh.id}`, "PUT", { status: "approved", baseUpdatedAt: fresh.updatedAt }, "browser-test-token"), newContext);
  const newVersion = (await newApproval.json()).data.updatedAt;
  const newClaim = await task.PATCH(request(newPath, "PATCH", { action: "claim", workerId: "new-author", baseUpdatedAt: newVersion }), newContext);
  const ownership = await newClaim.json();
  const session = taskSessionSchema.parse({ origin: "http://localhost:3000", id: fresh.id, updatedAt: ownership.data.updatedAt, claimToken: ownership.claimToken });
  assert.throws(() => taskSessionSchema.parse({ ...session, origin: "https://evil.invalid" }));
  assert.throws(() => collectionTaskRequest("propose", { ...proposal, published: true }));
  const draftSpec = taskRequest("draft", { session, input: candidate, requestId: randomUUID() });
  response = await draft.POST(request(draftSpec.path, draftSpec.method, draftSpec.body), newContext);
  assert.equal(response.status, 201);
  const slug = taskDraftSlug(fresh.id);
  assert.equal(posts.get(slug)!.published, false);
  assert.equal((await draft.POST(request(draftSpec.path, draftSpec.method, draftSpec.body), newContext)).status, 200);
  assert.equal((await draft.POST(request(draftPath, "POST", { ...draftSpec.body, candidate: { ...candidate, published: true } }), newContext)).status, 400);
  assert.equal((await draft.POST(request(draftPath, "POST", { ...draftSpec.body, candidate: { ...candidate, title: "다른 원고로 덮어쓰는 요청" } }), newContext)).status, 409);
  const submitSpec = taskRequest("submit", { session, input: { kind: "draft", postSlug: slug, summary: "새 비공개 원고의 검증을 완료했습니다." }, requestId: randomUUID() });
  response = await task.PATCH(request(submitSpec.path, submitSpec.method, submitSpec.body), newContext);
  assert.equal(response.status, 200);
  let reviewed = (await response.json()).data;
  assert.equal(reviewed.status, "review");
  assert.equal(reviewed.brief.result.postSlug, slug);
  assert.equal(posts.get(slug)!.published, false, "Submitting for review must never publish");
  response = await human.PUT(request(`/api/admin/content-planner/${fresh.id}`, "PUT", { status: "in_progress", baseUpdatedAt: reviewed.updatedAt }, "browser-test-token"), newContext);
  const reopened = (await response.json()).data;
  assert.equal(reopened.sourceSnapshot.taskWorkflow.leaseExpiresAt, null);
  assert.equal((await task.PATCH(request(newPath, "PATCH", { action: "progress", baseUpdatedAt: reopened.updatedAt, claimToken: session.claimToken, message: "이전 토큰으로 보고" }), newContext)).status, 409);
  response = await human.PUT(request(`/api/admin/content-planner/${fresh.id}`, "PUT", { status: "published", baseUpdatedAt: reopened.updatedAt }, "browser-test-token"), newContext);
  reviewed = (await response.json()).data;
  assert.equal(reviewed.status, "published");
  assert.equal(posts.get(slug)!.published, false, "Task completion does not replace human publication");
  assert.equal(classifyAgentContentAccess(secret, "POST", draftPath, secrets), "agent:content");
  console.log("Content tasks verified: proposal idempotency, human approval, claim race CAS, token privacy, progress, expiry, target validation, replay and restricted permissions.");
}
void verify().catch(error => { console.error(error instanceof assert.AssertionError ? error.message : "Content task verification failed"); process.exitCode = 1; }).finally(() => { globalThis.fetch = originalFetch; });
